#include "vita_save.cpp"
#include "vita_cform_ground.h"
#include <cassert>
#include <filesystem>
#include <iostream>
#include <fstream>
int main(int argc,char**argv){
 assert(argc==3);std::filesystem::create_directories(argv[2]);
 FILE*f=fopen(argv[1],"rb");assert(f);VitaCformGround ground;
 const auto reader=[](void*p,void*out,size_t n){return fread(out,1,n,(FILE*)p)==n;};
 assert(ground.load(reader,f,std::filesystem::file_size(argv[1]),32,-264,{},nullptr,true));fclose(f);
 VitaGarbageRoad road;assert(road.restore({},ground)&&road.ready);
 for(unsigned i=0;i<4;++i){const auto&a=i?road.battle.guards[i-1]:road.battle.scouts[0];
  assert(std::hypot(a.position[0]-vita_garbage_road_spawns[i][0],a.position[2]-vita_garbage_road_spawns[i][2])<.01f);
  std::cout<<"actor="<<i<<" floor="<<a.position[1]<<"\n";
 }
 auto initial=road.state();
 for(uint64_t now=1;now<2000000;now+=33333)assert(road.update(ground,now,{0,0,0},100).empty());
 assert(road.flags==1&&!road.battle.active);
 unsigned shots=0;
 for(uint64_t now=2000000;now<16000000;now+=33333)shots+=road.update(ground,now,{33,.5f,-278},100).size();
 assert(shots&&road.flags&2);
 std::cout<<"shots="<<shots<<" cleared="<<road.cleared()<<"\n";
 // Bodies remain dead and the survivor stays in the same place after load and map roundtrips.
 road.battle.guards[0].health=0;
 VitaSaveState state;state.zone=1;state.story=3;state.health=100;
 VitaInventory inventory;inventory.grant_starting_equipment();inventory.receive_flash();inventory.deliver_flash();state.inventory=inventory.state();
 state.garbage_road=road.state();state.eye={33,2.2f,-278};state.ground=.5f;state.guards.fill(2);
 assert(valid(state));assert(write_vita_slot(argv[2],0,state));
 VitaSaveState loaded;assert(read_vita_slot(argv[2],0,loaded));
 assert(loaded.garbage_road.health==state.garbage_road.health&&loaded.garbage_road.position==state.garbage_road.position);
 VitaGarbageRoad resumed;assert(resumed.restore(loaded.garbage_road,ground));
 assert(!resumed.battle.guards[0].health);
 VitaSaveState agroprom,back;
 assert(change_vita_zone(loaded,vita_zone_exits[2],agroprom));
 assert(change_vita_zone(agroprom,vita_zone_exits[3],back));
 assert(back.garbage_road.health==state.garbage_road.health&&back.garbage_road.position==state.garbage_road.position);
 auto bad=state;bad.garbage_road.health[1]=3;assert(!write_vita_slot(argv[2],1,bad));
 bad=state;bad.garbage_road.position[0][0]=3000;assert(!write_vita_slot(argv[2],1,bad));
 // Format 6 data generated by the prior format, without the new 68-byte tail.
 auto old=encode(state,1);old.resize(version6_bytes-4);old[4]=6;
 for(unsigned i=0;i<4;++i)old[16+i]=uint8_t(version6_bytes>>(i*8));
 const auto hash=checksum(old);for(unsigned i=0;i<4;++i)old.push_back(uint8_t(hash>>(i*8)));
 VitaSaveState migrated;uint64_t generation=0;
 assert(decode_record(old,migrated,generation)&&migrated.zone==1&&migrated.garbage_road.flags==0);
 assert(migrated.inventory.items==state.inventory.items);
 std::cout<<"Road CFORM placement, combat, health/position persistence, map roundtrip, v6 migration and corruption passed\n";
}
